# Writes elegance-sys's declarations of Elegance's C API from its C header (include/elg-c/elegance.h
# in the pinned commit's package, or c/include/elg-c/elegance.h in an Elegance checkout):
#   src/bindings.rs   every function, struct, handle type and constant, by bindgen, and the hash of
#                     the header they come from (ELEGANCE_HEADER_HASH), which build.rs compares with
#                     the header of the library it links
#   src/layouts.rs    each struct's size, alignment and field offsets as Rust lays them out, which
#                     the layout test compares with what the library reports
# Run it whenever the pin moves to a commit whose header changed. It needs bindgen
# (cargo install bindgen-cli) and libclang.
#
#   python3 elegance-sys/generate.py <path to elegance.h>

import os
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
LICENSE = """// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.
// If a copy of the MPL was not distributed with this file, You can obtain one at
// https://mozilla.org/MPL/2.0/."""
KEYWORDS = {"type", "match", "ref", "move", "fn", "impl", "mod", "use", "loop", "box", "self", "in", "where"}


def fnv1a(data):
    """64-bit FNV-1a, as build.rs computes it."""
    value = 0xCBF29CE484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return value


def bindgen(header):
    environment = dict(os.environ)
    environment.setdefault("RUSTUP_TOOLCHAIN", "stable")
    output = subprocess.run(
        ["bindgen", str(header), "--allowlist-function", "elg_.*", "--allowlist-type", "Elg.*", "--allowlist-var",
         "ELG_.*", "--with-derive-default", "--no-layout-tests", "--", "-std=c11"],
        capture_output=True, text=True, check=True, env=environment).stdout
    # A field's trailing doc comment (///<) keeps its "<".
    return re.sub(r'#\[doc = "< ', '#[doc = " ', output)


def layouts(bindings):
    entries = []
    for match in re.finditer(r"pub struct (Elg\w+) \{\n(.*?)\n\}", bindings, re.S):
        fields = re.findall(r"^\s*pub (r#)?(\w+): ", match[2], re.M)
        if not fields:
            continue  # an opaque handle
        name = match[1]
        parts = []
        for raw, field in fields:
            rust = f"{raw}{field}"
            c_name = field[:-1] if field.endswith("_") and field[:-1] in KEYWORDS else field
            parts.append(f'("{c_name}", offset_of!({name}, {rust}))')
        entries.append(f'    ("{name}", size_of::<{name}>(), align_of::<{name}>(), &[{", ".join(parts)}]),')
    return f"""{LICENSE}

// Generated by generate.py from Elegance's C header; don't edit.

use crate::*;
use core::mem::{{align_of, offset_of, size_of}};

/// A struct as Rust lays it out: its name, size and alignment, and each field's name (the C one)
/// and offset, in order.
pub type Layout = (&'static str, usize, usize, &'static [(&'static str, usize)]);

/// Each struct the C API passes.
pub const LAYOUTS: &[Layout] = &[
{chr(10).join(entries)}
];
"""


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: generate.py <path to elegance.h>")
    header = pathlib.Path(sys.argv[1])
    bindings = bindgen(header)
    digest = fnv1a(header.read_bytes())
    text = f"""{LICENSE}

// Generated by generate.py with bindgen from Elegance's C header (include/elg-c/elegance.h); don't
// edit. lib.rs includes it.

/// The FNV-1a hash of the header these declarations come from: build.rs refuses a library whose
/// header has another one.
pub const ELEGANCE_HEADER_HASH: u64 = {digest:#018x};

{bindings}"""
    (HERE / "src" / "bindings.rs").write_text(text, encoding="utf-8")
    (HERE / "src" / "layouts.rs").write_text(layouts(bindings), encoding="utf-8")
    print(f"generate.py: wrote src/bindings.rs and src/layouts.rs from {header} ({digest:#018x})")


if __name__ == "__main__":
    main()
